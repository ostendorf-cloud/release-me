// files is a ReadFile over a fixed set of repository files.
func files(contents map[string]string) migrate.ReadFile {
	return func(path string) ([]byte, error) {
		if c, ok := contents[path]; ok {
			return []byte(c), nil
		}
		return nil, fs.ErrNotExist
	}
}

// load loads translated YAML the way every command does, so a test fails
// on a translation release-me itself would refuse.
func load(t *testing.T, content []byte) config.Config {
	t.Helper()
	path := filepath.Join(t.TempDir(), "release-me.yaml")
	if err := os.WriteFile(path, content, 0o600); err != nil {
		t.Fatal(err)
	}
	cfg, err := config.Load(path)
	if err != nil {
		t.Fatalf("config.Load() error = %v, content:\n%s", err, content)
	}
	return cfg
}

// monorepoConfig is a release-please-config.json for a node monorepo with
// component-prefixed "@" tags and the main package's changelog kept at the
// repository root.
const monorepoConfig = `{
  "$schema": "https://raw.githubusercontent.com/googleapis/release-please/main/schemas/config.json",
  "release-type": "node",
  "include-component-in-tag": true,
  "tag-separator": "@",
  "include-v-in-tag": true,
  "bump-minor-pre-major": true,
  "bump-patch-for-minor-pre-major": false,
  "last-release-sha": "04bc8c0ff942285c5b5fb03895a589220c0d5a92",
  "packages": {
    "packages/duxt": {
      "package-name": "@kirchdev/duxt",
      "changelog-path": "/CHANGELOG.md"
    },
    "packages/duxt-typesense": {
      "package-name": "@kirchdev/duxt-typesense",
      "changelog-path": "CHANGELOG.md",
      "initial-version": "0.1.0"
    }
  }
}`

const monorepoManifest = `{
  "packages/duxt": "0.8.1",
  "packages/duxt-typesense": "0.1.0"
}`

func TestFromReleasePleaseTranslatesAComponentTaggedMonorepo(t *testing.T) {
	t.Parallel()

	read := files(map[string]string{
		"packages/duxt/package.json":           `{"name": "@kirchdev/duxt", "version": "0.8.1"}`,
		"packages/duxt-typesense/package.json": `{"name": "@kirchdev/duxt-typesense", "version": "0.1.0"}`,
	})
	got, err := migrate.FromReleasePlease([]byte(monorepoConfig), []byte(monorepoManifest), read)
	if err != nil {
		t.Fatalf("FromReleasePlease() error = %v", err)
	}

	want := `# Generated by release-me migrate release-please.
changelog-source: all
release-pull-request: shared
labels:
  pending: 'autorelease: pending'
  tagged: 'autorelease: tagged'
  alpha: false
  beta: false
  rc: false
bump-minor-pre-major: true
components:
  duxt:
    path: packages/duxt
    tag-prefix: duxt@v
    changelog: CHANGELOG.md
    files:
      - path: packages/duxt/package.json
        updater: json
        key: version
  duxt-typesense:
    path: packages/duxt-typesense
    tag-prefix: duxt-typesense@v
    initial-version: 0.1.0
    files:
      - path: packages/duxt-typesense/package.json
        updater: json
        key: version
`
	if string(got.YAML) != want {
		t.Fatalf("YAML =\n%s\nwant\n%s", got.YAML, want)
	}

	cfg := load(t, got.YAML)
	resolved := cfg.Resolve()
	if resolved[0].TagPrefix != "duxt@v" || resolved[0].ChangelogPath != "CHANGELOG.md" {
		t.Fatalf("duxt resolves to tag prefix %q and changelog %q", resolved[0].TagPrefix, resolved[0].ChangelogPath)
	}
	if resolved[1].ChangelogPath != "packages/duxt-typesense/CHANGELOG.md" {
		t.Fatalf("duxt-typesense changelog = %q", resolved[1].ChangelogPath)
	}

	wantTags := []migrate.ExpectedTag{
		{Component: "duxt", Tag: "duxt@v0.8.1"},
		{Component: "duxt-typesense", Tag: "duxt-typesense@v0.1.0"},
	}
	if !reflect.DeepEqual(got.Tags, wantTags) {
		t.Fatalf("Tags = %+v, want %+v", got.Tags, wantTags)
	}

	wantWarnings := []string{
		"last-release-sha: not needed, release-me reads the history since each component's last tag",
	}
	if !reflect.DeepEqual(got.Warnings, wantWarnings) {
		t.Fatalf("Warnings = %q, want %q", got.Warnings, wantWarnings)
	}
}

func TestFromReleasePleaseMapsSeparatePullRequestsToReleasePullRequest(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name       string
		configJSON string
		want       config.ReleasePullRequest
		wantKey    bool
	}{
		{
			name:       "left out groups every package, release-please's default",
			configJSON: `{"packages": {"web": {"component": "web"}, "api": {"component": "api"}}}`,
			want:       config.ReleasePullRequestShared, wantKey: true,
		},
		{
			name:       "false groups every package",
			configJSON: `{"separate-pull-requests": false, "packages": {"web": {"component": "web"}, "api": {"component": "api"}}}`,
			want:       config.ReleasePullRequestShared, wantKey: true,
		},
		{
			name:       "true opens one per package",
			configJSON: `{"separate-pull-requests": true, "packages": {"web": {"component": "web"}, "api": {"component": "api"}}}`,
			want:       config.ReleasePullRequestPerComponent,
		},
		{
			name: "a linked-versions group over every package is locked, which always shares one",
			configJSON: `{"plugins": [{"type": "linked-versions", "groupName": "family", "components": ["web", "api"]}],
			  "packages": {"web": {"component": "web"}, "api": {"component": "api"}}}`,
			want: config.ReleasePullRequestShared,
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := migrate.FromReleasePlease([]byte(tc.configJSON), nil, files(nil))
			if err != nil {
				t.Fatalf("FromReleasePlease() error = %v", err)
			}
			if cfg := load(t, got.YAML); cfg.ReleasePullRequest != tc.want {
				t.Fatalf("ReleasePullRequest = %q, want %q\n%s", cfg.ReleasePullRequest, tc.want, got.YAML)
			}
			if strings.Contains(string(got.YAML), "release-pull-request:") != tc.wantKey {
				t.Fatalf("YAML =\n%s\nwant release-pull-request written only where it differs from the default", got.YAML)
			}
			for _, w := range got.Warnings {
				if strings.Contains(w, "separate-pull-requests") {
					t.Fatalf("Warnings = %q, want none for separate-pull-requests, it carries over", got.Warnings)
				}
			}
		})
	}
}

func TestFromReleasePleaseCarriesOverBumpPatchForMinorPreMajor(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name       string
		configJSON string
		wantTop    bool
		wantComps  []bool
	}{
		{
			name: "a top-level default every package inherits is written once at the top level",
			configJSON: `{"bump-patch-for-minor-pre-major": true, "release-type": "go",
			  "packages": {"web": {"component": "web"}, "api": {"component": "api"}}}`,
			wantTop:   true,
			wantComps: []bool{true, true},
		},
		{
			name: "a package's own value stays on its component",
			configJSON: `{"release-type": "go", "packages": {
			  "web": {"component": "web", "bump-patch-for-minor-pre-major": true}, "api": {"component": "api"}}}`,
			wantComps: []bool{true, false},
		},
		{
			name:       "a single root package carries it at the top level",
			configJSON: `{"packages": {".": {"release-type": "go", "bump-patch-for-minor-pre-major": true}}}`,
			wantTop:    true,
			wantComps:  []bool{true},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := migrate.FromReleasePlease([]byte(tc.configJSON), nil, files(nil))
			if err != nil {
				t.Fatalf("FromReleasePlease() error = %v", err)
			}
			cfg := load(t, got.YAML)
			if cfg.BumpPatchForMinorPreMajor != tc.wantTop {
				t.Fatalf("BumpPatchForMinorPreMajor = %v, want %v\n%s", cfg.BumpPatchForMinorPreMajor, tc.wantTop, got.YAML)
			}
			var comps []bool
			for _, c := range cfg.Resolve() {
				comps = append(comps, c.BumpPatchForMinorPreMajor)
			}
			if !reflect.DeepEqual(comps, tc.wantComps) {
				t.Fatalf("components = %v, want %v\n%s", comps, tc.wantComps, got.YAML)
			}
			for _, w := range got.Warnings {
				if strings.Contains(w, "bump-patch-for-minor-pre-major") {
					t.Fatalf("Warnings = %q, want none for bump-patch-for-minor-pre-major, it carries over", got.Warnings)
				}
			}
		})
	}
}

